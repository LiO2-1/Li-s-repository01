package com.qiyuesan.variable;

public class VariableDemo3 {
    public static void main(String[] args) {
        //目标：掌握常见的数据类型的使用
        // 1.byte short int long
        byte a =127;   //-128~127
        short b =3313;
        int c =24444;  //默认
        //若需要使用long型数据，需要在数据后增加"L/l".
        long d =1999999111119L;

        //2.float double
        float e =3.14F;
        //若需要使用float型数据，需要在数据后增加"F/f".
        double f =56.56; //默认

        //3.char
        char g ='a';
        char h ='中';

        //4.boolean
        boolean j =true;
        boolean k =false;

        /*拓展
        String 称为字符串类型   */
        String l ="李国兴";


    }
}
