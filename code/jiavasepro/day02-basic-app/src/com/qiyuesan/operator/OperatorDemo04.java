package com.qiyuesan.operator;

public class OperatorDemo04 {
    public static void main(String[] args) {
        // 掌握关系运算符的基本使用
        int a =10;
        int b =5;
        boolean tf = a>b;
        System.out.println(tf);      //true

        System.out.println(a >= b);  //true

        System.out.println(a < b);   //false

        System.out.println(a <= b);  //false

        System.out.println(a == b);  //false

        System.out.println(a != b);  //true




    }
}
